/**
 * Dossier Manifest Generator Metadata
 */
export interface ManifestGeneratorInfo {
  software: string;
  version: string;
  jurisdictionProfile: string;
}

/**
 * Case metadata within the dossier manifest
 */
export interface ManifestCaseInfo {
  caseId: string;
  title: string;
  category: string;
  exportTimestampUtc: string;
}

/**
 * Cryptographic trust seal embedded within the dossier manifest
 */
export interface ManifestTrustSeal {
  digestAlgorithm: 'SHA-256';
  manifestContentSha256: string;
  canonicalizationAlgorithm: 'RFC8785_JCS';
  signatureAlgorithm: 'ED25519';
  signingKeyId: string;
  serverDigitalSignature: string;
  verificationEndpoint: string;
}

/**
 * Unsealed trust seal representation (before serverDigitalSignature is computed)
 */
export interface UnsealedTrustSeal {
  digestAlgorithm: 'SHA-256';
  manifestContentSha256: string;
  canonicalizationAlgorithm: 'RFC8785_JCS';
  signatureAlgorithm: 'ED25519';
  signingKeyId: string;
  verificationEndpoint: string;
  serverDigitalSignature?: string;
}

/**
 * Evidence file record within the dossier manifest
 */
export interface ManifestFileEntry {
  evidenceId: string;
  packageRelativePath: string;
  originalFilename: string;
  mediaType: string;
  fileSizeBytes: number;
  sha256: string;
  systemReceiptUtc: string;
  sourceClassification: string;
}

/**
 * Complete, digitally sealed VeraTrace Dossier Manifest (veratrace_manifest.v1.json)
 */
export interface DossierManifest {
  $schema: string;
  manifestVersion: number;
  generator: ManifestGeneratorInfo;
  case: ManifestCaseInfo;
  trustSeal: ManifestTrustSeal;
  files: ManifestFileEntry[];
  disclaimers: string[];
}

/**
 * Unsealed Dossier Manifest awaiting Ed25519 digital signature
 */
export interface UnsealedDossierManifest {
  $schema: string;
  manifestVersion: number;
  generator: ManifestGeneratorInfo;
  case: ManifestCaseInfo;
  trustSeal?: Partial<UnsealedTrustSeal>;
  files: ManifestFileEntry[];
  disclaimers: string[];
}

/**
 * Input options for building a manifest
 */
export interface ManifestBuildOptions {
  software?: string;
  version?: string;
  jurisdictionProfile?: string;
  signingKeyId?: string;
  verificationEndpoint?: string;
  disclaimers?: string[];
  exportTimestampUtc?: string;
}

/**
 * Key status in the published public keyset
 */
export type PublicKeyStatus = 'ACTIVE' | 'DEPRECATED' | 'REVOKED';

/**
 * Entry within published Ed25519 public keyset (veratrace-public-keys.json)
 */
export interface PublicKeyEntry {
  keyId: string;
  algorithm: 'Ed25519' | 'ED25519';
  status: PublicKeyStatus;
  validFromUtc?: string;
  validUntilUtc?: string;
  publicKeyPem: string;
  revokedAtUtc?: string;
  revocationReason?: string;
}

/**
 * Published public keyset structure
 */
export interface PublicKeyset {
  $schema: string;
  keys: PublicKeyEntry[];
}

/**
 * Verification state machine overall outcome status
 * Matches Blueprint Section 11.1 + Module J Standalone Archive Verification
 */
export type VerificationOutcomeStatus =
  | 'MATCH'
  | 'MISMATCH'
  | 'INVALID_MANIFEST'
  | 'INCOMPLETE'
  | 'MALFORMED_ARCHIVE';

/**
 * Recognized auxiliary packaging artifacts in a standard VeraTrace Dossier ZIP.
 * These are integral parts of the dossier package created by Module I and are not
 * treated as unexpected extra files during manifest integrity audits.
 */
export const KNOWN_AUXILIARY_DOSSIER_PATHS = Object.freeze([
  'veratrace_manifest.v1.json',
  'manifest.json',
  'dossier_index.json',
] as const);

/**
 * Configuration options for verifying an entire ZIP dossier archive directly.
 */
export interface VerifyZipDossierOptions {
  /**
   * Pinned or out-of-band authenticated keyset.
   * MITIGATING THE CIRCULAR TRUST TRAP: Must NOT be loaded from inside an untrusted archive.
   */
  trustedKeyset?: PublicKeyset | PublicKeyEntry[];
  /**
   * Direct trusted public key PEM (convenience for single-key out-of-band trust anchors)
   */
  trustedPublicKeyPem?: string;
  /**
   * Maximum allowed uncompressed size in bytes across all entries (zip bomb mitigation).
   * Default: 500MB (524,288,000 bytes)
   */
  maxUncompressedSizeBytes?: number;
  /**
   * Maximum allowed number of archive entries (zip bomb mitigation).
   * Default: 10,000 entries
   */
  maxEntriesCount?: number;
}

/**
 * Comprehensive verification report returned by Module J Offline ZIP Verifier.
 */
export interface ZipDossierVerificationReport extends VerificationReport {
  /**
   * Whether the ZIP archive itself was valid, structurally sound, and free of path traversal
   */
  archiveValid: boolean;
  /**
   * Details if the archive itself is malformed, corrupted, or contains security violations
   */
  archiveError?: string;
  /**
   * Raw or parsed dossier index if present in archive (dossier_index.json)
   */
  dossierIndex?: unknown;
  /**
   * Total archive entries safely inspected in memory
   */
  archiveEntriesCount: number;
}

/**
 * Per-file verification result
 */
export interface VerificationFileResultItem {
  packageRelativePath: string;
  evidenceId?: string;
  expectedSha256: string;
  calculatedSha256?: string;
  status: 'MATCH' | 'MISMATCH' | 'FILE_MISSING' | 'UNEXPECTED_FILE';
  details?: string;
}

/**
 * Comprehensive verification report returned by Module J Offline Verifier
 */
export interface VerificationReport {
  overallStatus: VerificationOutcomeStatus;
  verificationMode: 'OFFLINE_ASYMMETRIC' | 'ONLINE_SERVER_RECORD';
  checkedFilesCount: number;
  mismatchedFilesCount: number;
  missingFilesCount: number;
  unexpectedFilesCount: number;
  signatureValid: boolean;
  signingKeyId?: string;
  keyStatus?: PublicKeyStatus | 'UNTRUSTED';
  manifestContentSha256Matches: boolean;
  executionNotes: string;
  verifiedAtUtc: string;
  fileResults: VerificationFileResultItem[];
}
